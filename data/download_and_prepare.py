import os
import sys
import zipfile
import urllib.request
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = DATA_DIR.parent

SPIDER_URL = "https://raw.githubusercontent.com/Yale-LILY/Spider/master/data/spider.zip"
SPIDER_REALISTIC_URL = "https://huggingface.co/datasets/aherntech/spider-realistic/raw/main/spider-realistic.json"

def download_file(url: str, dest_path: Path):
    def progress_hook(block_num, block_size, total_size):
        downloaded = block_num * block_size
        if total_size > 0:
            percent = downloaded / total_size * 100
            sys.stdout.write(f"\rDownloading: {percent:.1f}% ({downloaded / (1024*1024):.1f} MB)")
            sys.stdout.flush()

    urllib.request.urlretrieve(url, dest_path, reporthook=progress_hook)
    print()

def extract_zip(zip_path: Path, extract_to: Path):
    with zipfile.ZipFile(zip_path, 'r') as zip_ref:
        zip_ref.extractall(extract_to)

def main():
    DATA_DIR.mkdir(parents=True, exist_ok=True)

    spider_zip = DATA_DIR / "spider.zip"
    spider_extracted = DATA_DIR / "spider_temp"

    if not (DATA_DIR / "database").exists() or not (DATA_DIR / "spider_dev.json").exists():
        if not spider_zip.exists():
            download_file(SPIDER_URL, spider_zip)
        extract_zip(spider_zip, spider_extracted)

        src_db = spider_extracted / "spider" / "database" if (spider_extracted / "spider" / "database").exists() else spider_extracted / "database"
        dest_db = DATA_DIR / "database"
        if not dest_db.exists() and src_db.exists():
            src_db.rename(dest_db)

        src_dev = spider_extracted / "spider" / "dev.json" if (spider_extracted / "spider" / "dev.json").exists() else spider_extracted / "dev.json"
        if src_dev.exists() and not (DATA_DIR / "spider_dev.json").exists():
            src_dev.rename(DATA_DIR / "spider_dev.json")

        src_train = spider_extracted / "spider" / "train_spider.json" if (spider_extracted / "spider" / "train_spider.json").exists() else spider_extracted / "train_spider.json"
        if src_train.exists() and not (DATA_DIR / "train_spider.json").exists():
            src_train.rename(DATA_DIR / "train_spider.json")

        if spider_zip.exists(): os.remove(spider_zip)
        if spider_extracted.exists():
            import shutil
            shutil.rmtree(spider_extracted, ignore_errors=True)

    realistic_file = DATA_DIR / "spider_realistic.json"
    if not realistic_file.exists():
        try:
            download_file(SPIDER_REALISTIC_URL, realistic_file)
        except Exception:
            pass

if __name__ == "__main__":
    main()