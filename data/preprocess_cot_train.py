import os
import re
import json
import sqlite3
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parent
DB_DIR = DATA_DIR / "database"
OUTPUT_DIR = DATA_DIR / "processed"

def extract_schema_ddl(db_path: Path) -> str:
    """Trích xuất lược đồ DDL SQLite sạch."""
    if not db_path.exists():
        return ""
    try:
        conn = sqlite3.connect(str(db_path))
        cursor = conn.cursor()
        cursor.execute("SELECT sql FROM sqlite_master WHERE type='table' AND sql IS NOT NULL;")
        tables = [re.sub(r'\s+', ' ', row[0]).strip() for row in cursor.fetchall() if row[0]]
        conn.close()
        return "\n".join(tables)
    except Exception:
        return ""

def synthesize_cot_reasoning(question: str, sql: str, schema_ddl: str) -> str:
    """Tổng hợp vết suy luận logic chuẩn hóa."""
    tables_found = []
    for line in schema_ddl.splitlines():
        m = re.search(r'CREATE\s+TABLE\s+[`"\[]?(\w+)[`"\]]?', line, re.IGNORECASE)
        if m:
            tbl = m.group(1)
            if re.search(rf'\b{tbl}\b', sql, re.IGNORECASE):
                tables_found.append(tbl)

    table_str = ", ".join(tables_found) if tables_found else "the required tables"

    reasoning = (
        f"<think>\n"
        f"1. Goal Analysis: The user asks: \"{question}\".\n"
        f"2. Schema Linking: Map relevant entities to table(s) [{table_str}].\n"
        f"3. Query Formulation: Apply necessary filters, projections, and SQLite syntax constraints.\n"
        f"</think>\n"
        f"```sql\n{sql}\n```"
    )
    return reasoning

def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    dev_path = DATA_DIR / "spider_dev.json"
    realistic_path = DATA_DIR / "spider_realistic.json"
    train_path = DATA_DIR / "train_spider.json"

    if not dev_path.exists() or not train_path.exists():
        return

    with open(dev_path, "r", encoding="utf-8") as f:
        dev_data = json.load(f)
    dev_db_ids = set(s["db_id"] for s in dev_data)

    if realistic_path.exists():
        with open(realistic_path, "r", encoding="utf-8") as f:
            realistic_data = json.load(f)
        eval_db_ids = dev_db_ids.union(set(s["db_id"] for s in realistic_data))
    else:
        eval_db_ids = dev_db_ids

    with open(train_path, "r", encoding="utf-8") as f:
        train_raw = json.load(f)

    clean_candidates = [s for s in train_raw if s["db_id"] not in eval_db_ids]

    cot_samples = []
    TARGET_SIZE = 800

    for s in clean_candidates:
        if len(cot_samples) >= TARGET_SIZE:
            break
        db_path = DB_DIR / s["db_id"] / f"{s['db_id']}.sqlite"
        if not db_path.exists():
            continue
        sch = extract_schema_ddl(db_path)
        if not sch:
            continue

        cot_assistant_text = synthesize_cot_reasoning(s["question"], s["query"], sch)

        full_sample = {
            "db_id": s["db_id"],
            "question": s["question"],
            "query": s["query"],
            "schema": sch,
            "prompt_text": (
                f"<|im_start|>system\n"
                f"You are a SQLite expert that reasons carefully before generating SQL queries.<|im_end|>\n"
                f"<|im_start|>user\n"
                f"Database Schema:\n{sch}\n\n"
                f"User Question: {s['question']}\n\n"
                f"Instructions:\n"
                f"1. Think step-by-step inside <think> ... </think> tags.\n"
                f"2. Output the final valid SQLite query enclosed in ```sql ... ``` tags.<|im_end|>\n"
                f"<|im_start|>assistant\n"
                f"{cot_assistant_text}<|im_end|>"
            )
        }
        cot_samples.append(full_sample)

    output_file = OUTPUT_DIR / "cot_train_800.json"
    with open(output_file, "w", encoding="utf-8") as f:
        json.dump(cot_samples, f, indent=2, ensure_ascii=False)

if __name__ == "__main__":
    main()