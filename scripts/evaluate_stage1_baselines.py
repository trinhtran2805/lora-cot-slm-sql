def print_summary_table(records):
    df = pd.DataFrame(records)
    total = len(df)
    methods = [
        ("M1", "M1: Zero-Shot Baseline"),
        ("M2", "M2: Dynamic ICL (Light-SQL)"),
        ("M3", "M3: Schema Pruning (Hong et al.)"),
        ("M4", "M4: Fine-Tuned LoRA (Ours)")
    ]
    difficulties = ["Easy", "Medium", "Hard", "Extra Hard"]

    rows = []
    for tag, name in methods:
        row = {"Method": name}
        for diff in difficulties:
            sub = df[df["difficulty"] == diff]
            if len(sub) > 0:
                corr = (sub[f"{tag}_status"] == "CORRECT").sum()
                row[diff] = f"{(corr/len(sub))*100:.2f}% ({corr}/{len(sub)})"
            else:
                row[diff] = "N/A"
        overall = (df[f"{tag}_status"] == "CORRECT").sum()
        syn = (df[f"{tag}_status"] == "SYNTAX_ERROR").sum()
        row["Overall EX"] = f"{(overall/total)*100:.2f}% ({overall}/{total})"
        row["Syntax Error"] = f"{(syn/total)*100:.2f}%"
        rows.append(row)

    print("\n" + "="*115)
    print("BANG TONG KET DOI SACH STAGE 1 (YALE SPIDER DEV SET - 1.034 CAU)")
    print("="*115)
    print(tabulate(pd.DataFrame(rows), headers="keys", tablefmt="fancy_grid", showindex=False))

