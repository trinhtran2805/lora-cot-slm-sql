import os
import json
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
JSON_DIR = PROJECT_ROOT / "artifacts" / "results_json"
FIG_DIR = PROJECT_ROOT / "artifacts" / "figures"
FIG_DIR.mkdir(parents=True, exist_ok=True)

sns.set_theme(style="whitegrid", font="sans-serif")

def plot_stage1_figures():
    s1_file = JSON_DIR / "stage1_eval_checkpoint.json"
    if not s1_file.exists():
        return

    with open(s1_file, "r", encoding="utf-8") as f:
        records = json.load(f)
    df = pd.DataFrame(records)
    total = len(df)

    methods = [
        ("M1", "M1: Zero-Shot"),
        ("M2", "M2: Light-SQL (ICL)"),
        ("M3", "M3: Schema Pruning"),
        ("M4", "M4: LoRA (Ours)")
    ]
    difficulties = ["Easy", "Medium", "Hard", "Extra Hard"]

    chart_data = []
    for tag, name in methods:
        for diff in difficulties:
            sub = df[df["difficulty"] == diff]
            rate = (sub[f"{tag}_status"] == "CORRECT").sum() / len(sub) * 100 if len(sub) > 0 else 0
            chart_data.append({"Method": name, "Difficulty": diff, "Execution Accuracy (%)": rate})
        overall_rate = (df[f"{tag}_status"] == "CORRECT").sum() / total * 100
        chart_data.append({"Method": name, "Difficulty": "Overall", "Execution Accuracy (%)": overall_rate})

    df_chart = pd.DataFrame(chart_data)

    fig, axes = plt.subplots(1, 2, figsize=(16, 5))

    sns.barplot(
        data=df_chart,
        x="Difficulty",
        y="Execution Accuracy (%)",
        hue="Method",
        palette="Blues_r",
        ax=axes[0]
    )
    axes[0].set_title("Stage 1: Execution Accuracy Across Yale Spider Difficulty", fontsize=12, fontweight='bold')
    axes[0].set_ylim(0, 100)
    axes[0].set_ylabel("Execution Accuracy (EX %)")
    axes[0].legend(loc="upper right", frameon=True)

    syn_rates = [(df[f"{tag}_status"] == "SYNTAX_ERROR").sum() / total * 100 for tag, _ in methods]
    bars = axes[1].bar([m[0] for m in methods], syn_rates, color=['#e74c3c', '#e67e22', '#f39c12', '#27ae60'], width=0.45)
    axes[1].set_title("SQLite Syntax Error Rate Before Self-Repair (%)", fontsize=12, fontweight='bold')
    axes[1].set_ylabel("Error Rate (%)")
    axes[1].set_ylim(0, 100)
    for b in bars:
        axes[1].text(b.get_x() + b.get_width()/2, b.get_height() + 1.5, f"{b.get_height():.1f}%", ha='center', fontweight='bold')

    plt.tight_layout()
    out_path = FIG_DIR / "stage1_spider_publication_plots.png"
    plt.savefig(out_path, dpi=300)
    plt.close()

def plot_stage2_figures():
    s2_file = JSON_DIR / "stage2_self_repair_results.json"
    if not s2_file.exists():
        return

    with open(s2_file, "r", encoding="utf-8") as f:
        records = json.load(f)
    df = pd.DataFrame(records)
    total = len(df)

    pre_stats = {
        "M1": (198, 799, "M1: Zero-Shot"),
        "M2": (348, 587, "M2: Light-SQL"),
        "M3": (169, 828, "M3: Schema Pruning"),
        "M4": (639, 189, "M4: LoRA")
    }

    labels = [v[2] for v in pre_stats.values()]
    pre_rates = [v[0] / total * 100 for v in pre_stats.values()]
    post_rates = [((df[f"{k}_post_status"] == "CORRECT").sum() / total) * 100 for k in pre_stats.keys()]
    recovery_rates = [
        ((df[f"{k}_post_status"] == "CORRECT").sum() - v[0]) / v[1] * 100 if v[1] > 0 else 0
        for k, v in pre_stats.items()
    ]

    fig, axes = plt.subplots(1, 2, figsize=(16, 5))
    x = np.arange(len(labels))
    w = 0.35

    axes[0].bar(x - w/2, pre_rates, w, label='Pre-Repair EX', color='#7f8c8d')
    b2 = axes[0].bar(x + w/2, post_rates, w, label='Post-Repair EX', color='#2ecc71')
    axes[0].set_title("Execution Accuracy: Pre-Repair vs. Post-Repair", fontsize=12, fontweight='bold')
    axes[0].set_ylabel("Execution Accuracy (%)")
    axes[0].set_xticks(x)
    axes[0].set_xticklabels(labels)
    axes[0].set_ylim(0, 100)
    axes[0].legend(loc="upper left")
    for b in b2:
        axes[0].text(b.get_x() + b.get_width()/2, b.get_height() + 1.2, f"{b.get_height():.1f}%", ha='center', fontweight='bold')

    bars_rec = axes[1].bar(labels, recovery_rates, color=['#3498db', '#e67e22', '#9b59b6', '#27ae60'], width=0.45)
    axes[1].set_title("Syntax Error Recovery Rate (%)", fontsize=12, fontweight='bold')
    axes[1].set_ylabel("Recovery Rate (%)")
    axes[1].set_ylim(0, max(recovery_rates) + 15 if max(recovery_rates) > 0 else 50)
    for b in bars_rec:
        axes[1].text(b.get_x() + b.get_width()/2, b.get_height() + 1.0, f"{b.get_height():.1f}%", ha='center', fontweight='bold')

    plt.tight_layout()
    out_path = FIG_DIR / "stage2_publication_results.png"
    plt.savefig(out_path, dpi=300)
    plt.close()

if __name__ == "__main__":
    plot_stage1_figures()
    plot_stage2_figures()