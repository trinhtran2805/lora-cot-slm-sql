import os
import sys
import json
import torch
from pathlib import Path
from transformers import AutoModelForCausalLM, AutoTokenizer, TrainingArguments, Trainer, DataCollatorForSeq2Seq
from peft import LoraConfig, get_peft_model, TaskType

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.append(str(PROJECT_ROOT))

def main():
    with open(PROJECT_ROOT / "configs" / "lora_config.json", "r", encoding="utf-8") as f:
        lora_cfg = json.load(f)
    with open(PROJECT_ROOT / "configs" / "train_config.json", "r", encoding="utf-8") as f:
        train_cfg = json.load(f)

    model_id = train_cfg["model_id"]
    output_dir = PROJECT_ROOT / "artifacts" / "checkpoints" / "lora_adapter"
    output_dir.mkdir(parents=True, exist_ok=True)

    tokenizer = AutoTokenizer.from_pretrained(model_id, trust_remote_code=True)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    model = AutoModelForCausalLM.from_pretrained(
        model_id,
        torch_dtype=torch.float16,
        device_map="cuda:0" if torch.cuda.is_available() else "cpu",
        trust_remote_code=True
    )

    cot_data_file = PROJECT_ROOT / "data" / "processed" / "cot_train_800.json"
    if cot_data_file.exists():
        with open(cot_data_file, "r", encoding="utf-8") as f:
            cot_samples = json.load(f)
        training_texts = [s["prompt_text"] for s in cot_samples]
    else:
        return

    encodings = tokenizer(
        training_texts,
        truncation=True,
        max_length=train_cfg["max_seq_length"],
        padding=True,
        return_tensors="pt"
    )

    class SpiderDataset(torch.utils.data.Dataset):
        def __init__(self, enc): self.enc = enc
        def __len__(self): return len(self.enc.input_ids)
        def __getitem__(self, idx):
            item = {k: v[idx] for k, v in self.enc.items()}
            item["labels"] = item["input_ids"].clone()
            return item

    peft_config = LoraConfig(**lora_cfg)
    peft_model = get_peft_model(model, peft_config)

    training_args = TrainingArguments(
        output_dir=str(output_dir),
        per_device_train_batch_size=train_cfg["per_device_train_batch_size"],
        gradient_accumulation_steps=train_cfg["gradient_accumulation_steps"],
        learning_rate=train_cfg["learning_rate"],
        max_steps=train_cfg["max_steps"],
        fp16=train_cfg["fp16"] and torch.cuda.is_available(),
        logging_steps=train_cfg["logging_steps"],
        save_strategy=train_cfg["save_strategy"],
        report_to="none"
    )

    trainer = Trainer(
        model=peft_model,
        args=training_args,
        train_dataset=SpiderDataset(encodings),
        data_collator=DataCollatorForSeq2Seq(tokenizer, pad_to_multiple_of=8, return_tensors="pt", padding=True)
    )

    trainer.train()
    peft_model.save_pretrained(str(output_dir))
    tokenizer.save_pretrained(str(output_dir))

if __name__ == "__main__":
    main()