def compare_query_result_rows(
    gold_rows: List[Tuple[object, ...]],
    predicted_rows: List[Tuple[object, ...]],
    order_sensitive: bool = False,
) -> bool:
    """Compare SQLite rows with Spider-style ordering and duplicate semantics."""
    def normalize(value):
        if value is None:
            return ("__SQL_NULL__",)
        try:
            if bool(value != value):
                return ("__SQL_NULL__",)
        except (TypeError, ValueError):
            pass
        return value

    gold = [tuple(normalize(value) for value in row) for row in gold_rows]
    predicted = [tuple(normalize(value) for value in row) for row in predicted_rows]
    if order_sensitive:
        return gold == predicted
    try:
        return Counter(gold) == Counter(predicted)
    except TypeError:
        return sorted(map(repr, gold)) == sorted(map(repr, predicted))


def query_has_order_by(sql_query: str) -> bool:
    """Detect ORDER BY outside SQL strings, quoted identifiers, and comments."""
    non_code = re.compile(
        r"""'(?:''|[^'])*'|"(?:\"\"|[^"])*"|`(?:``|[^`])*`|"""
        r"""\[(?:\]\]|[^\]])*\]|--[^\r\n]*|/\*[\s\S]*?\*/"""
    )
    code = non_code.sub(" ", sql_query)
    return re.search(r"\bORDER\s+BY\b", code, flags=re.IGNORECASE) is not None


