import os
import re
import sqlite3
import pandas as pd
from pathlib import Path
from typing import Tuple, Union

def execute_query(db_path: Union[str, Path], sql_query: str) -> Tuple[bool, Union[pd.DataFrame, str]]:
    """
    Thực thi câu truy vấn trực tiếp trên Engine SQLite.
    Trả về: (Status: bool, DataFrame kết quả / Ngoại lệ lỗi Runtime).
    """
    db_path = Path(db_path)
    if not db_path.exists() or not sql_query:
        return False, "Database path or SQL query is missing"
    try:
        conn = sqlite3.connect(str(db_path))
        df = pd.read_sql_query(sql_query, conn)
        conn.close()
        return True, df
    except Exception as e:
        return False, str(e)

def compare_results(df_gold: pd.DataFrame, df_pred: pd.DataFrame) -> bool:
    """
    So khớp tập giá trị đầu ra (Execution Accuracy - EX) chuẩn Yale Spider.
    Bỏ qua sai khác về tên cột hiển thị hoặc thứ tự dòng (nếu không có ORDER BY).
    """
    if df_gold is None or df_pred is None:
        return False
    if df_gold.equals(df_pred):
        return True
    try:
        # Chuẩn hóa giá trị: Làm phẳng và sắp xếp chuỗi để so sánh đối xứng
        val_gold = sorted(df_gold.astype(str).values.flatten().tolist())
        val_pred = sorted(df_pred.astype(str).values.flatten().tolist())
        return val_gold == val_pred
    except Exception:
        return False

def clean_sql_from_response(raw_text: str) -> str:
    """
    Bóc tách SQL sạch từ đầu ra của LLM/SLM.
    Xử lý triệt để: Cắt bỏ khối suy luận <think>...</think>, loại bỏ Markdown và comment.
    """
    # 1. Triệt tiêu khối suy luận CoT nếu có
    text_clean = re.sub(r'<think>[\s\S]*?</think>', '', raw_text, flags=re.IGNORECASE).strip()

    # 2. Trích xuất khối mã ```sql ... ```
    match = re.search(r"```(?:sql)?\s*([\s\S]*?)(?:```|$)", text_clean, re.IGNORECASE)
    if match and len(match.group(1).strip()) > 3:
        query = match.group(1).strip()
    else:
        # Dự phòng: Bắt đầu từ từ khóa SELECT
        match_sel = re.search(r"(SELECT\s+[\s\S]+)", text_clean, re.IGNORECASE)
        query = match_sel.group(1).strip() if match_sel else text_clean.strip()

    # 3. Cắt dấu chấm phẩy và loại bỏ các dòng comment
    if ";" in query:
        query = query.split(";")[0]

    lines = [l.strip() for l in query.splitlines() if not l.strip().startswith(("--", "#"))]
    return " ".join(lines).strip()

def evaluate_sql_difficulty(sql: str) -> str:
    """
    Phân loại độ khó SQL chuẩn Yale Spider Benchmark dựa trên độ phức tạp cú pháp:
    - Easy: Không JOIN hoặc JOIN cơ bản, không lồng ghép.
    - Medium: Gom nhóm GROUP BY, HAVING, ORDER BY.
    - Hard: JOIN nhiều bảng kết hợp hàm tổng hợp.
    - Extra Hard: Phép toán tập hợp (INTERSECT, UNION, EXCEPT) hoặc Subquery lồng ghép.
    """
    sql_upper = sql.upper()
    score = 0

    joins = len(re.findall(r'\bJOIN\b', sql_upper))
    score += joins * 1

    if "GROUP BY" in sql_upper: score += 1
    if "ORDER BY" in sql_upper: score += 1
    if "HAVING" in sql_upper: score += 2
    if "LIMIT" in sql_upper: score += 1

    agg_funcs = len(re.findall(r'\b(COUNT|AVG|SUM|MIN|MAX)\s*\(', sql_upper))
    if agg_funcs > 1: score += 1

    if any(op in sql_upper for op in ["INTERSECT", "EXCEPT", "UNION"]):
        score += 3

    subqueries = len(re.findall(r'\bSELECT\b', sql_upper)) - 1
    if subqueries > 0:
        score += subqueries * 2

    if score <= 1:
        return "Easy"
    elif score <= 3:
        return "Medium"
    elif score <= 5:
        return "Hard"
    else:
        return "Extra Hard"