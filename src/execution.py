def execute_readonly_query(
    db_path: Union[str, Path],
    sql_query: str,
    timeout_seconds: float = 30.0
) -> Tuple[bool, Union[List[Tuple[object, ...]], str]]:
    """Execute one generated or gold query without allowing database writes."""
    db_path = Path(db_path)
    if not db_path.is_file() or not sql_query.strip():
        return False, "Database path or SQL query is missing"

    deadline = time.monotonic() + timeout_seconds
    connection = None
    try:
        database_uri = f"{db_path.resolve().as_uri()}?mode=ro"
        connection = sqlite3.connect(database_uri, uri=True, timeout=timeout_seconds)
        connection.text_factory = bytes
        connection.execute("PRAGMA query_only = ON")
        connection.set_progress_handler(
            lambda: 1 if time.monotonic() >= deadline else 0,
            1000
        )
        cursor = connection.execute(sql_query)
        return True, cursor.fetchall()
    except sqlite3.Error as error:
        return False, str(error)
    finally:
        if connection is not None:
            connection.close()

