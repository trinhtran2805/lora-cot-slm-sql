def synthesize_cot_reasoning(question: str, sql: str, schema_ddl: str) -> str:
    """
    Sinh cấu trúc suy luận CoT chuẩn để gắn nhãn dữ liệu huấn luyện hoặc ví dụ Few-shot.
    """
    import re
    tables_found = []
    for line in schema_ddl.splitlines():
        m = re.search(r'CREATE\s+TABLE\s+[`"\[]?(\w+)[`"\]]?', line, re.IGNORECASE)
        if m:
            tbl = m.group(1)
            if re.search(rf'\b{tbl}\b', sql, re.IGNORECASE):
                tables_found.append(tbl)

    table_str = ", ".join(tables_found) if tables_found else "the required tables"

    return (
        f"<think>\n"
        f"1. Goal Analysis: The user asks: \"{question}\".\n"
        f"2. Schema Linking: Map relevant entities to table(s) [{table_str}].\n"
        f"3. Query Formulation: Apply necessary filters, projections, and SQLite syntax constraints.\n"
        f"</think>\n"
        f"```sql\n{sql}\n```"
    )