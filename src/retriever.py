"""
Module Truy xuất Ngữ nghĩa Động (Dynamic ICL Retriever) chuẩn bài báo Light-SQL.
"""

import torch
from pathlib import Path
from typing import Dict, List, Union
from sentence_transformers import SentenceTransformer
from src.schema_engine import extract_schema_ddl, locate_database_path
from src.prompts import synthesize_cot_reasoning

class DynamicICLRetriever:
    def __init__(self, train_pool: List[Dict], db_root_dir: Union[str, Path] = "data/database", device: str = None):
        if device is None:
            self.device = "cuda" if torch.cuda.is_available() else "cpu"
        else:
            self.device = device

        self.db_root_dir = Path(db_root_dir)
        self.train_pool = train_pool
        self.encoder = SentenceTransformer('all-MiniLM-L6-v2', device=self.device)

        # Mã hóa toàn bộ câu hỏi trong tập huấn luyện
        self.candidate_questions = [item["question"] for item in train_pool]
        self.candidate_embeddings = self.encoder.encode(
            self.candidate_questions,
            convert_to_tensor=True,
            show_progress_bar=False,
            device=self.device
        )

    def retrieve_exemplars(self, question: str, top_k: int = 2, with_cot: bool = True) -> str:
        """Truy xuất top-k ví dụ tương đồng nhất về mặt ý định ngữ nghĩa."""
        q_emb = self.encoder.encode(question, convert_to_tensor=True, device=self.device)
        cos_scores = torch.nn.functional.cosine_similarity(q_emb, self.candidate_embeddings)
        top_indices = torch.topk(cos_scores, k=top_k).indices.tolist()

        exemplars = []
        for rank, idx in enumerate(top_indices, 1):
            sample = self.train_pool[idx]
            db_path = locate_database_path(sample["db_id"], self.db_root_dir)
            sch_ddl = extract_schema_ddl(db_path) if db_path.exists() else ""

            if with_cot:
                cot_block = synthesize_cot_reasoning(sample["question"], sample["query"], sch_ddl)
                exemplars.append(f"-- Example {rank}:\nUser Question: {sample['question']}\n{cot_block}")
            else:
                exemplars.append(f"-- Example Question: {sample['question']}\n{sample['query']};")

        return "\n\n".join(exemplars)

    def build_dynamic_prompt(self, schema: str, question: str, top_k: int = 2, with_cot: bool = True) -> str:
        """Sinh Prompt hoàn chỉnh chứa các ví dụ động."""
        fewshot_blocks = self.retrieve_exemplars(question, top_k=top_k, with_cot=with_cot)
        if with_cot:
            return (
                f"Database Schema:\n{schema}\n\n"
                f"Here are some examples of step-by-step reasoning and corresponding SQL queries for similar questions:\n"
                f"{fewshot_blocks}\n\n"
                f"Target User Question: {question}\n\n"
                f"Instructions:\n"
                f"1. First, think step-by-step inside <think> ... </think> tags to analyze target tables, schema linking, and join paths.\n"
                f"2. Output the final valid SQLite query enclosed in ```sql ... ``` tags."
            )
        else:
            return (
                f"Database Schema:\n{schema}\n\n"
                f"Here are reference examples for similar questions:\n"
                f"{fewshot_blocks}\n\n"
                f"Target Question: {question}\n"
                f"Return ONLY the executable SQL query enclosed in ```sql ... ``` tags."
            )