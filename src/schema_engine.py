"""
Module trích xuất Lược đồ CSDL và Duyệt Đồ thị Khóa ngoại (FK Graph).
Hỗ trợ phương pháp Cắt tỉa lược đồ (Schema Pruning) bảo toàn bảng cầu nối (Bridge Tables).
"""

import os
import re
import sqlite3
from collections import deque
from pathlib import Path
from typing import Dict, List, Set, Tuple, Union

def locate_database_path(db_id: str, db_root_dir: Union[str, Path] = "data/database") -> Path:
    """
    Định vị linh hoạt đường dẫn tệp .sqlite đa nền tảng.
    Hỗ trợ cả môi trường Local Repo, Linux, Windows và Colab.
    """
    db_root = Path(db_root_dir)
    candidates = [
        db_root / db_id / f"{db_id}.sqlite",
        db_root / f"{db_id}.sqlite",
        Path("data") / db_id / f"{db_id}.sqlite",
        Path("spider") / "database" / db_id / f"{db_id}.sqlite"
    ]
    for p in candidates:
        if p.exists():
            return p
    return db_root / db_id / f"{db_id}.sqlite"

def get_db_tables_and_fks(db_path: Union[str, Path]) -> Tuple[Dict[str, str], Dict[str, Set[str]]]:
    """
    Trích xuất DDL các bảng và xây dựng Đồ thị Vô hướng Khóa ngoại (Adjacency List).
    """
    db_path = Path(db_path)
    if not db_path.exists():
        return {}, {}

    conn = sqlite3.connect(str(db_path))
    cursor = conn.cursor()

    # 1. Trích xuất DDL nguyên bản
    cursor.execute("SELECT name, sql FROM sqlite_master WHERE type='table' AND sql IS NOT NULL;")
    tables = cursor.fetchall()
    table_ddls = {name.lower(): re.sub(r'\s+', ' ', ddl).strip() for name, ddl in tables if ddl}

    # 2. Xây dựng đồ thị liên kết Khóa ngoại
    fk_graph = {tbl: set() for tbl in table_ddls.keys()}
    for tbl in table_ddls.keys():
        try:
            cursor.execute(f"PRAGMA foreign_key_list('{tbl}');")
            fks = cursor.fetchall()
            for fk in fks:
                target_table = fk[2].lower()
                if target_table in fk_graph:
                    fk_graph[tbl].add(target_table)
                    fk_graph[target_table].add(tbl)
        except Exception:
            continue

    conn.close()
    return table_ddls, fk_graph

def extract_schema_ddl(db_path: Union[str, Path]) -> str:
    """Trích xuất chuỗi DDL hoàn chỉnh của CSDL."""
    table_ddls, _ = get_db_tables_and_fks(db_path)
    return "\n".join(table_ddls.values())

def find_bridge_tables(fk_graph: Dict[str, Set[str]], start_tables: Set[str]) -> Set[str]:
    """
    Thuật toán duyệt theo chiều rộng (BFS) tìm đường dẫn ngắn nhất trên Đồ thị Khóa ngoại
    nhằm khôi phục các Bảng Cầu Nối (Bridge Tables) bị Schema Pruning loại bỏ nhầm.
    """
    if len(start_tables) <= 1:
        return start_tables

    all_needed = set(start_tables)
    starts = list(start_tables)

    for i in range(len(starts)):
        for j in range(i + 1, len(starts)):
            t1, t2 = starts[i], starts[j]
            queue = deque([[t1]])
            visited = {t1}
            found_path = None

            while queue:
                path = queue.popleft()
                node = path[-1]
                if node == t2:
                    found_path = path
                    break
                for neighbor in fk_graph.get(node, []):
                    if neighbor not in visited:
                        visited.add(neighbor)
                        queue.append(path + [neighbor])

            if found_path:
                all_needed.update(found_path)

    return all_needed

def prune_schema_with_fk(db_path: Union[str, Path], question: str) -> str:
    """
    Cắt tỉa Lược đồ thông minh: Kết hợp so khớp từ vựng câu hỏi và bảo toàn liên kết FK.
    """
    table_ddls, fk_graph = get_db_tables_and_fks(db_path)
    if len(table_ddls) <= 2:
        return "\n".join(table_ddls.values())

    q_tokens = set(re.findall(r'\w+', question.lower()))
    hit_tables = set()

    for tbl_name, ddl in table_ddls.items():
        ddl_tokens = set(re.findall(r'\w+', ddl.lower()))
        overlap = q_tokens.intersection(ddl_tokens)
        if tbl_name in q_tokens or len(overlap) > 1:
            hit_tables.add(tbl_name)

    if not hit_tables:
        return "\n".join(table_ddls.values())

    # Khôi phục các bảng trung gian trên đồ thị FK
    complete_tables = find_bridge_tables(fk_graph, hit_tables)
    pruned_ddls = [table_ddls[tbl] for tbl in complete_tables if tbl in table_ddls]
    return "\n".join(pruned_ddls)